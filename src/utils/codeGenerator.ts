export interface GeneratorConfig {
  protocol: 'TCP' | 'UDP';
  concurrency: 'ITERATIVE' | 'THREAD_POOL' | 'NIO_SELECTOR';
  appType: 'ECHO' | 'CHAT' | 'CALCULATOR' | 'STUDENT_DB' | 'HTTP_WEB';
  port: number;
  bufferSize: number;
  timeoutMs: number;
  autoFlush: boolean;
  enableReuseAddr: boolean;
}

export function generateCustomJavaCode(config: GeneratorConfig): {
  serverCode: string;
  clientCode: string;
  serverFilename: string;
  clientFilename: string;
  compileCmd: string;
  runServerCmd: string;
  runClientCmd: string;
} {
  const { protocol, concurrency, appType, port, autoFlush, enableReuseAddr, timeoutMs } = config;

  if (protocol === 'UDP') {
    const serverFilename = 'CustomUdpServer.java';
    const clientFilename = 'CustomUdpClient.java';

    const serverCode = `import java.io.IOException;
import java.net.DatagramPacket;
import java.net.DatagramSocket;
import java.net.InetAddress;

/**
 * Custom UDP Server
 * Generated by BIT Network Programming Studio
 * Port: ${port}
 */
public class CustomUdpServer {
    public static final int PORT = ${port};
    public static final int BUFFER_SIZE = ${config.bufferSize};

    public static void main(String[] args) {
        System.out.println("Starting Custom UDP Server on port " + PORT + "...");

        try (DatagramSocket socket = new DatagramSocket(PORT)) {
            System.out.println("UDP Server listening. Connectionless mode active.");
            byte[] buffer = new byte[BUFFER_SIZE];

            while (true) {
                DatagramPacket packet = new DatagramPacket(buffer, buffer.length);
                socket.receive(packet); // Blocks until datagram arrives

                String message = new String(packet.getData(), 0, packet.getLength()).trim();
                InetAddress clientAddr = packet.getAddress();
                int clientPort = packet.getPort();

                System.out.println("Received: '" + message + "' from " + clientAddr + ":" + clientPort);

                // Application logic
                String response = "REPLY: " + message.toUpperCase();
                byte[] replyData = response.getBytes();

                DatagramPacket replyPacket = new DatagramPacket(
                    replyData, replyData.length, clientAddr, clientPort
                );
                socket.send(replyPacket);
            }
        } catch (IOException e) {
            System.err.println("UDP Server error: " + e.getMessage());
        }
    }
}`;

    const clientCode = `import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.net.DatagramPacket;
import java.net.DatagramSocket;
import java.net.InetAddress;
import java.net.SocketTimeoutException;

/**
 * Custom UDP Client
 * Target: 127.0.0.1:${port}
 */
public class CustomUdpClient {
    public static final String SERVER_HOST = "127.0.0.1";
    public static final int SERVER_PORT = ${port};
    public static final int TIMEOUT = ${timeoutMs};

    public static void main(String[] args) {
        try (DatagramSocket socket = new DatagramSocket()) {
            socket.setSoTimeout(TIMEOUT);
            InetAddress address = InetAddress.getByName(SERVER_HOST);
            BufferedReader stdIn = new BufferedReader(new InputStreamReader(System.in));

            System.out.println("UDP Client started. Enter message to send (or 'exit'):");
            String line;

            while ((line = stdIn.readLine()) != null) {
                if ("exit".equalsIgnoreCase(line.trim())) break;

                byte[] data = line.getBytes();
                DatagramPacket sendPacket = new DatagramPacket(data, data.length, address, SERVER_PORT);
                socket.send(sendPacket);

                try {
                    byte[] receiveBuffer = new byte[1024];
                    DatagramPacket receivePacket = new DatagramPacket(receiveBuffer, receiveBuffer.length);
                    socket.receive(receivePacket);

                    String reply = new String(receivePacket.getData(), 0, receivePacket.getLength());
                    System.out.println("Server reply: " + reply);
                } catch (SocketTimeoutException e) {
                    System.err.println("Timeout: No response received from server within " + TIMEOUT + "ms");
                }
            }
        } catch (Exception e) {
            System.err.println("Client error: " + e.getMessage());
        }
    }
}`;

    return {
      serverCode,
      clientCode,
      serverFilename,
      clientFilename,
      compileCmd: `javac ${serverFilename} ${clientFilename}`,
      runServerCmd: `java CustomUdpServer`,
      runClientCmd: `java CustomUdpClient`,
    };
  }

  // TCP Implementation
  const serverFilename = 'CustomTcpServer.java';
  const clientFilename = 'CustomTcpClient.java';

  const reuseSnippet = enableReuseAddr ? `\n        serverSocket.setReuseAddress(true);` : '';

  let appLogicSnippet = '';
  if (appType === 'CALCULATOR') {
    appLogicSnippet = `
                // Math Calculator logic: e.g. "ADD 10 20" or "MUL 5 6"
                String[] tokens = line.split("\\\\s+");
                if (tokens.length == 3) {
                    try {
                        String op = tokens[0].toUpperCase();
                        double a = Double.parseDouble(tokens[1]);
                        double b = Double.parseDouble(tokens[2]);
                        double res = 0;
                        switch (op) {
                            case "ADD" -> res = a + b;
                            case "SUB" -> res = a - b;
                            case "MUL" -> res = a * b;
                            case "DIV" -> res = (b != 0) ? (a / b) : Double.NaN;
                        }
                        out.println("RESULT: " + res);
                    } catch (NumberFormatException e) {
                        out.println("ERROR: Invalid operands. Use: ADD/SUB/MUL/DIV num1 num2");
                    }
                } else {
                    out.println("CALC FORMAT: <OP> <NUM1> <NUM2> (e.g. ADD 15 25)");
                }`;
  } else if (appType === 'STUDENT_DB') {
    appLogicSnippet = `
                if (line.startsWith("GET ")) {
                    String id = line.substring(4).trim();
                    out.println("STUDENT_RECORD: ID=" + id + " | Status=ACTIVE | Major=BIT");
                } else {
                    out.println("PROTOCOL: Send 'GET <STUDENT_ID>'");
                }`;
  } else {
    appLogicSnippet = `
                out.println("ECHO: " + line);`;
  }

  const serverCode = `import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.io.PrintWriter;
import java.net.ServerSocket;
import java.net.Socket;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;

/**
 * Custom TCP Server
 * Concurrency: ${concurrency}
 * Protocol Type: ${appType}
 * Port: ${port}
 */
public class CustomTcpServer {
    public static final int PORT = ${port};

    public static void main(String[] args) {
        System.out.println("Starting Custom TCP Server on port " + PORT + "...");
        ${concurrency === 'THREAD_POOL' ? 'ExecutorService threadPool = Executors.newFixedThreadPool(10);\n' : ''}
        try (ServerSocket serverSocket = new ServerSocket(PORT)) {${reuseSnippet}
            System.out.println("Server listening on port " + PORT + ". Ready for connections.");

            while (true) {
                Socket clientSocket = serverSocket.accept();
                System.out.println("Client connected: " + clientSocket.getRemoteSocketAddress());
                ${
                  concurrency === 'THREAD_POOL'
                    ? 'threadPool.execute(() -> handleClient(clientSocket));'
                    : 'handleClient(clientSocket);'
                }
            }
        } catch (IOException e) {
            System.err.println("Server exception: " + e.getMessage());
        }
    }

    private static void handleClient(Socket socket) {
        try (
            BufferedReader in = new BufferedReader(new InputStreamReader(socket.getInputStream()));
            PrintWriter out = new PrintWriter(socket.getOutputStream(), ${autoFlush})
        ) {
            out.println("SERVER: Connected to Custom Server. Mode: ${appType}");

            String line;
            while ((line = in.readLine()) != null) {
                System.out.println("Received: " + line);
                if ("QUIT".equalsIgnoreCase(line.trim())) {
                    out.println("SERVER: Closing session.");
                    break;
                }
${appLogicSnippet}
            }
        } catch (IOException e) {
            System.err.println("Handler error: " + e.getMessage());
        } finally {
            try { socket.close(); } catch (IOException ignored) {}
        }
    }
}`;

  const clientCode = `import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.PrintWriter;
import java.net.Socket;

/**
 * Custom TCP Client
 * Connects to 127.0.0.1:${port}
 */
public class CustomTcpClient {
    public static final String HOST = "127.0.0.1";
    public static final int PORT = ${port};

    public static void main(String[] args) {
        try (
            Socket socket = new Socket(HOST, PORT);
            PrintWriter out = new PrintWriter(socket.getOutputStream(), ${autoFlush});
            BufferedReader in = new BufferedReader(new InputStreamReader(socket.getInputStream()));
            BufferedReader stdIn = new BufferedReader(new InputStreamReader(System.in))
        ) {
            System.out.println("Connected to server! " + in.readLine());

            String line;
            System.out.print("> ");
            while ((line = stdIn.readLine()) != null) {
                out.println(line);
                String reply = in.readLine();
                if (reply == null) break;
                System.out.println("< " + reply);

                if ("QUIT".equalsIgnoreCase(line.trim())) break;
                System.out.print("> ");
            }
        } catch (Exception e) {
            System.err.println("Client error: " + e.getMessage());
        }
    }
}`;

  return {
    serverCode,
    clientCode,
    serverFilename,
    clientFilename,
    compileCmd: `javac ${serverFilename} ${clientFilename}`,
    runServerCmd: `java CustomTcpServer`,
    runClientCmd: `java CustomTcpClient`,
  };
}
